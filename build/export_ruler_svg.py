#!/usr/bin/env python3
"""Export the fin calibration scale as a printable 1:1 SVG.

Writes scads_v1/fin_ruler_scale_v<VERSION.json version>.svg from
fin_ruler_scale_2d() in lib/fin_ruler.scad -- the same ticks, labels and
+-fr_half_range() span as the engraved fin rulers, so one print fits both the
head (front) and the rear fin. Older fin_ruler_scale_v*.svg files are removed.
Stdlib + OpenSCAD only. Print at 100 % / actual size.

The numbers are set in Mulish Regular (v6.6.8), from the vendored
build/fonts/Mulish-Regular.ttf (SIL OFL, build/fonts/OFL.txt). OpenSCAD turns
them into outlines, so the SVG needs no font to print. The file is loaded
explicitly because fontconfig may otherwise give a different weight (on the
maintainer's machine "Mulish Regular" resolves to the installed Medium).
The engraved fins keep the font-free stroke digits.
"""
from __future__ import annotations
import re
import subprocess
import sys
import tempfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from scad_lib import find_openscad, read_version, repo_root  # noqa: E402

FONT_FILE = Path(__file__).resolve().parent / 'fonts' / 'Mulish-Regular.ttf'
FONT = 'Mulish:style=Regular'
MARGIN = 3.0        # mm of white paper around the scale, inside the cut line
CAPTION = 7.0       # mm reserved under the scale for the caption


def main() -> int:
    root = repo_root()
    version = read_version()
    out = root / 'scads_v1' / f'fin_ruler_scale_v{version}.svg'
    with tempfile.TemporaryDirectory() as td:
        src = Path(td) / 'scale.scad'
        raw = Path(td) / 'scale.svg'
        if not FONT_FILE.is_file():
            raise SystemExit(f'Missing {FONT_FILE}')
        src.write_text(f'use <{FONT_FILE}>\nuse <{root}/lib/fin_ruler.scad>\n'
                       f'fin_ruler_scale_2d(font="{FONT}");\n')
        subprocess.run([find_openscad(), '-o', str(raw), str(src)], check=True,
                       capture_output=True, text=True)
        text = raw.read_text()
    box = re.search(r'viewBox="([-\d.]+) ([-\d.]+) ([-\d.]+) ([-\d.]+)"', text)
    path = re.search(r'<path d="(.*?)"', text, re.S)
    if not box or not path:
        raise SystemExit('Unexpected OpenSCAD SVG output')
    x, y, w, h = map(float, box.groups())
    # OpenSCAD writes SVG with Y flipped (Y down), so +mm is at the top.
    bx, by = x - MARGIN, y - MARGIN
    bw, bh = w + 2 * MARGIN, h + 2 * MARGIN + CAPTION
    cap_y = y + h + MARGIN + 2.6
    svg = f'''<?xml version="1.0" encoding="UTF-8"?>
<!-- GENERATED by build/export_ruler_svg.py from lib/fin_ruler.scad (turtle_body v{version}). Do not hand-edit. -->
<!-- Print at 100 % (actual size). Check: the +30 and -30 ticks are 60 mm apart. -->
<svg xmlns="http://www.w3.org/2000/svg" version="1.1" width="{bw:g}mm" height="{bh:g}mm" viewBox="{bx:g} {by:g} {bw:g} {bh:g}">
<title>Hope Turtle fin ruler scale v{version}</title>
<rect x="{bx:g}" y="{by:g}" width="{bw:g}" height="{bh:g}" fill="white" stroke="#999" stroke-width="0.2" stroke-dasharray="1 1"/>
<path fill="black" stroke="none" d="{path.group(1)}"/>
<text x="{x + w / 2:g}" y="{cap_y:g}" font-family="Mulish, sans-serif" font-size="1.7" text-anchor="middle">Hope Turtle fin ruler</text>
<text x="{x + w / 2:g}" y="{cap_y + 2.3:g}" font-family="Mulish, sans-serif" font-size="1.7" text-anchor="middle">v{version} · print 100%</text>
</svg>
'''
    for old in (root / 'scads_v1').glob('fin_ruler_scale_v*.svg'):
        if old != out:
            old.unlink()
    out.write_text(svg)
    print(f'wrote {out.relative_to(root)}  {bw:g} x {bh:g} mm')
    return 0


if __name__ == '__main__':
    sys.exit(main())
